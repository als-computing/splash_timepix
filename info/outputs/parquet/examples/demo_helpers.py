"""Process plumbing for ``demo_for_review.ipynb``.

Starts and stops the three processes the demonstration needs — ``tpx-stream`` (the streaming
server with parquet on), ``tpx-sim`` (the simulated detector) and ``tiled serve catalog`` (a
throw-away Tiled server on a SQLite catalog) — so the notebook cells show only what the reader
is meant to check. Nothing here is specific to the notebook; it is the same command lines the
UI and the tests use, on free ports, under one temporary directory.

Everything runs on localhost with the repo's own tools. No detector, no ``live-cli``.
"""

from __future__ import annotations

import json
import logging
import os
import re
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Optional

import httpx

from splash_timepix.heartbeat import wait_for_ready
from splash_timepix.parquet_meta import SCAN_META_FILENAME

# Tiled refuses API keys with non-alphanumeric characters.
API_KEY = "demoapikey0123456789abcdef0123456789"

# The Tiled client logs every HTTP request at INFO once something configures logging, and
# draws a rich progress bar for multi-partition reads; both are noise in a notebook cell.
logging.getLogger("httpx").setLevel(logging.WARNING)
os.environ.setdefault("TILED_SHOW_PROGRESS", "0")

_SENT_RE = re.compile(r"Sent events during last session: (\d+) pixel, (\d+) TDC, (\d+) control")


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        s.listen(1)
        return s.getsockname()[1]


def _terminate(proc: Optional[subprocess.Popen], timeout: float = 15.0) -> None:
    if proc is None or proc.poll() is not None:
        return
    proc.terminate()
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(timeout=5)


class Demo:
    """One demonstration run: a data directory, a scan written into it, and a Tiled server.

    Typical use (what the notebook does)::

        demo = Demo()
        demo.start_stream(roll_mb=0.25, sample="Cu foil (demo)")
        demo.start_simulator(cps=200_000, duration=20)
        ...                              # look at the directory while data flows
        scan_dir = demo.wait_scan_finished()
        demo.start_tiled()
        ...                              # register, read back, search
        demo.restart_tiled()             # same catalog file, new process
        demo.close()
    """

    def __init__(self, workdir: Optional[Path] = None, keep: bool = False):
        self.workdir = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="tpx3_demo_"))
        self.workdir.mkdir(parents=True, exist_ok=True)
        self.keep = keep
        self.data_dir = self.workdir / "data"  # what the UI calls the output directory
        self.data_dir.mkdir(exist_ok=True)
        self.catalog_db = self.workdir / "catalog.db"
        self.logs = self.workdir / "logs"
        self.logs.mkdir(exist_ok=True)

        self.tcp_port = free_port()
        self.zmq_port = free_port()
        self.hb_port = free_port()
        self.tiled_port = free_port()
        self.tiled_uri = f"http://127.0.0.1:{self.tiled_port}"
        self.api_key = API_KEY

        self.tdc_frequency = 100.0
        self.meta_json = self.workdir / "demo_meta.json"
        self._stream: Optional[subprocess.Popen] = None
        self._sim: Optional[subprocess.Popen] = None
        self._tiled: Optional[subprocess.Popen] = None
        self._sim_log = self.logs / "tpx-sim.log"

    # ------------------------------------------------------------------ tpx-stream + tpx-sim

    def start_stream(
        self,
        *,
        roll_mb: float = 0.25,
        row_group_rows: int = 20_000,
        tdc_frequency: float = 100.0,
        sample: str = "Cu foil (demo)",
        esaf: str = "demo-0001",
        notes: str = "generated by demo_for_review.ipynb",
        detector: Optional[dict] = None,
        ready_timeout: float = 30.0,
    ) -> None:
        """Start ``tpx-stream`` with parquet on, exactly as the UI does for a Start run.

        The operator fields go through the same ``--parquet-meta-json`` file the UI writes;
        ``acq.py`` would add the detector snapshot to it on real hardware. ``roll_mb`` and
        ``row_group_rows`` are tiny here (defaults 512 MB / 1 M rows) so that files appear
        every few seconds at the demo's modest count rate.
        """
        self.tdc_frequency = tdc_frequency
        meta = {"user": {"sample": sample, "esaf": esaf, "notes": notes}}
        if detector is not None:
            # On real hardware acq.py writes this block from a Serval snapshot; a demo may
            # supply a placeholder that says the data is simulated.
            meta["detector"] = detector
        self.meta_json.write_text(json.dumps(meta))
        cmd = [
            sys.executable,
            "-m",
            "splash_timepix.app",
            "--host",
            "127.0.0.1",
            "--port",
            str(self.tcp_port),
            "--zmq-port",
            str(self.zmq_port),
            "--heartbeat-port",
            str(self.hb_port),
            "--tdc-frequency",
            str(tdc_frequency),
            "--flush-interval",
            "0.5",
            "--exit-on-disconnect",
            "--parquet-dir",
            str(self.data_dir),
            "--parquet-roll-mb",
            str(roll_mb),
            "--parquet-row-group-rows",
            str(row_group_rows),
            "--parquet-source",
            "simulator",
            "--parquet-meta-json",
            str(self.meta_json),
        ]
        log = open(self.logs / "tpx-stream.log", "wb")
        self._stream = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)
        if not wait_for_ready(port=self.hb_port, timeout=ready_timeout):
            _terminate(self._stream)
            raise RuntimeError(f"tpx-stream did not become ready; see {self.logs / 'tpx-stream.log'}")

    def start_simulator(self, *, cps: float = 15_000, duration: int = 20) -> None:
        """Start ``tpx-sim --auto-start``: connects, streams for ``duration`` s, disconnects.

        Keep ``cps`` well under what the pure-Python simulator can push through one socket
        (about 30 k packets/s on a quiet machine): above that its event backlog grows without
        bound and the run takes far longer than ``duration``. The real detector is not paced
        this way; see ``tools/bench_parquet_sink.py`` for the sink at 40 Mhit/s.
        """
        # The wrapper turns on INFO logging so the simulator's final "Sent events ..." line,
        # which is the ground truth for the row-count check, lands in the log file.
        wrapper = (
            "import logging, sys; logging.basicConfig(level=logging.INFO, format='%(message)s'); "
            "from splash_timepix.simulator_cli import app; app()"
        )
        cmd = [
            sys.executable,
            "-c",
            wrapper,
            "--auto-start",
            "--host",
            "127.0.0.1",
            "--port",
            str(self.tcp_port),
            "--tdc-frequency",
            str(self.tdc_frequency),
            "--cps",
            str(cps),
            "--duration",
            str(duration),
        ]
        log = open(self._sim_log, "wb")
        self._sim = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)

    @property
    def scan_dir(self) -> Optional[Path]:
        """The scan directory ``tpx-stream`` created (first one under ``data_dir``), or None yet."""
        dirs = sorted(p for p in self.data_dir.iterdir() if p.is_dir() and (p / "events").is_dir())
        return dirs[0] if dirs else None

    def wait_scan_dir(self, timeout: float = 30.0) -> Path:
        deadline = time.time() + timeout
        while time.time() < deadline:
            d = self.scan_dir
            if d is not None:
                return d
            time.sleep(0.2)
        raise TimeoutError("no scan directory appeared; is the simulator connected?")

    def wait_scan_finished(self, timeout: float = 120.0) -> Path:
        """Wait for the simulator to finish, the server to exit and ``_scan_meta.json`` to exist."""
        if self._sim is not None:
            self._sim.wait(timeout=timeout)
        if self._stream is not None:
            self._stream.wait(timeout=timeout)  # --exit-on-disconnect: exits after the stop
        scan_dir = self.wait_scan_dir()
        deadline = time.time() + 30
        while not (scan_dir / SCAN_META_FILENAME).exists() and time.time() < deadline:
            time.sleep(0.2)
        if not (scan_dir / SCAN_META_FILENAME).exists():
            raise RuntimeError(f"{SCAN_META_FILENAME} never appeared; see {self.logs / 'tpx-stream.log'}")
        return scan_dir

    def simulator_sent(self) -> dict:
        """Pixel / TDC / control counts the simulator reports it sent (from its log)."""
        text = self._sim_log.read_text(errors="replace") if self._sim_log.exists() else ""
        m = _SENT_RE.search(text)
        if not m:
            raise RuntimeError(f"simulator did not report its sent counts; see {self._sim_log}")
        return {"events": int(m.group(1)), "tdc": int(m.group(2)), "control": int(m.group(3))}

    # ------------------------------------------------------------------ Tiled

    def start_tiled(self, timeout: float = 60.0) -> str:
        """Start ``tiled serve catalog`` on this demo's catalog file; returns the URI.

        Same recipe as ``info/outputs/parquet/tiled.md``: ``--read`` points at the data
        directory so Tiled may serve the parquet files in place.
        """
        if self._tiled is not None and self._tiled.poll() is None:
            return self.tiled_uri
        cmd = [
            sys.executable,
            "-m",
            "tiled",
            "serve",
            "catalog",
            "--api-key",
            self.api_key,
            "--read",
            str(self.data_dir),
            "--host",
            "127.0.0.1",
            "--port",
            str(self.tiled_port),
            str(self.catalog_db),
        ]
        if not self.catalog_db.exists():
            cmd.insert(cmd.index("catalog") + 1, "--init")
        env = dict(os.environ)
        env.pop("TILED_API_KEY", None)
        log = open(self.logs / "tiled.log", "ab")
        self._tiled = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT, env=env)
        deadline = time.time() + timeout
        while time.time() < deadline and self._tiled.poll() is None:
            try:
                if httpx.get(f"{self.tiled_uri}/api/v1/", timeout=1.0).status_code < 500:
                    return self.tiled_uri
            except httpx.HTTPError:
                time.sleep(0.25)
        _terminate(self._tiled)
        raise RuntimeError(f"tiled serve catalog did not come up; see {self.logs / 'tiled.log'}")

    def stop_tiled(self) -> None:
        _terminate(self._tiled)
        self._tiled = None

    def restart_tiled(self) -> str:
        """Stop the Tiled process and start a new one on the same catalog file."""
        self.stop_tiled()
        return self.start_tiled()

    def tiled_client(self):
        """A Tiled client for this server, authenticated with the demo API key."""
        from tiled.client import from_uri

        return from_uri(self.tiled_uri, api_key=self.api_key)

    def register(self, scan_dir: Optional[Path] = None, path: str = "tpx3", **kwargs) -> dict:
        """Register the scan the way the UI does (``tpx-tiled-register`` in-process)."""
        from splash_timepix.tiled_register import connect, register_scan

        scan_dir = Path(scan_dir or self.wait_scan_dir())
        container = connect(self.tiled_uri, api_key=self.api_key, path=path)
        return register_scan(container, scan_dir, uri=self.tiled_uri, path=path, **kwargs)

    # ------------------------------------------------------------------ housekeeping

    def close(self) -> None:
        """Stop every process; delete the working directory unless ``keep``."""
        _terminate(self._sim)
        _terminate(self._stream)
        _terminate(self._tiled)
        self._sim = self._stream = self._tiled = None
        if not self.keep:
            shutil.rmtree(self.workdir, ignore_errors=True)

    def __enter__(self) -> "Demo":
        return self

    def __exit__(self, *exc) -> None:
        self.close()


def tree(root: Path, max_files: int = 6) -> str:
    """A compact directory listing with file sizes, for printing in a cell."""
    root = Path(root)
    lines = [f"{root.name}/"]
    for sub in sorted(root.iterdir()):
        if sub.is_dir():
            files = sorted(sub.iterdir())
            lines.append(f"  {sub.name}/  ({len(files)} files)")
            for f in files[:max_files]:
                lines.append(f"    {f.name:<28} {f.stat().st_size / 1e6:8.2f} MB")
            if len(files) > max_files:
                lines.append(f"    … {len(files) - max_files} more")
        else:
            lines.append(f"  {sub.name:<30} {sub.stat().st_size / 1e3:8.1f} kB")
    return "\n".join(lines)
